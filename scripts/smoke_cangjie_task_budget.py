"""Real deadlines, valid delayed responses, atomic commit and hard task limits."""

import json
import re
import subprocess
import time
from pathlib import Path
from uuid import uuid4


def task_budget(endpoint, env, query, token, state, create_question, create):
    from smoke_cangjie_learning_tasks import action, task_request, wait_task

    control = Path(env["CANGJIE_TEST_BUDGET_STATE"])
    events = Path(env["CANGJIE_TEST_BUDGET_EVENTS"])

    def trigger(sql):
        # Binlog-enabled MySQL requires the local admin to install test triggers.
        # This helper is restricted to the disposable database generated by verify.
        name = env["CANGJIE_DB_NAME"]
        assert re.fullmatch(r"zhiwei_cangjie_test_[0-9a-f]+", name)
        socket = env.get(
            "CANGJIE_TEST_MYSQL_SOCKET",
            str(Path(__file__).resolve().parents[1] / ".mysql-run/mysqld.sock"),
        )
        subprocess.run(
            ["mysql", "--socket=" + socket, "-uroot", "-D", name, "-e", sql],
            check=True,
            capture_output=True,
            text=True,
        )

    def rules(value):
        temp = control.with_suffix(".new")
        temp.write_text(json.dumps({"rules": value}))
        temp.replace(control)

    def log():
        try:
            return [
                json.loads(line) for line in events.read_text().splitlines() if line
            ]
        except FileNotFoundError:
            return []

    def wait_event(key, kind, maximum=55):
        end = time.monotonic() + maximum
        while True:
            result = next(
                (r for r in log() if r.get("key") == key and r.get("kind") == kind),
                None,
            )
            if result:
                return result
            assert time.monotonic() < end, "budget proxy event did not arrive"
            time.sleep(0.05)

    def wait(current, maximum=60):
        end = time.monotonic() + maximum
        while True:
            current = task_request(
                endpoint, f"/api/v1/learning-tasks/{current['id']}", token
            )
            if current["status"] not in {"queued", "running"}:
                return current
            assert time.monotonic() < end, "budget task did not reach a checkpoint"
            time.sleep(0.1)

    def submit(current, kind="resume", text="", expected=202, key=None):
        body = {
            "kind": kind,
            "text": text,
            "version": current["version"],
            "step_id": current["step_id"],
            "input_fingerprint": current["input_fingerprint"],
            "request_id": key or str(uuid4()),
        }
        return task_request(
            endpoint,
            f"/api/v1/learning-tasks/{current['id']}/actions",
            token,
            body,
            status=expected,
        ), body

    def counters(current):
        id = current["id"]
        return query(
            env,
            f"SELECT (SELECT COUNT(*) FROM learning_task_steps WHERE task_id='{id}'),(SELECT COUNT(*) FROM cognitive_updates WHERE JSON_UNQUOTE(JSON_EXTRACT(evidence,'$.learning_task_id'))='{id}'),(SELECT COUNT(*) FROM review_plans WHERE question_id='{current['question_id']}'),(SELECT COUNT(*) FROM learning_task_exposures WHERE task_id='{id}')",
        )

    try:
        slow = wait_task(endpoint, create(create_question(71))["id"], token)
        key = str(uuid4())
        rules(
            [
                {
                    "key": key,
                    "question_id": slow["question_id"],
                    "operation": "learning_task",
                    "delay_seconds": 41,
                }
            ]
        )
        start = time.monotonic()
        queued, _ = submit(slow)
        assert time.monotonic() - start < 2 and queued["status"] in {
            "queued",
            "running",
        }
        accepted = wait_event(key, "accepted", 5)
        assert 0 < accepted["task_budget_ms"] <= 38000
        failed = wait(queued, 50)
        elapsed = time.monotonic() - start
        assert failed["status"] == "failed" and 30 <= elapsed < 48
        assert not failed["learning_applied"]
        version = failed["version"]
        wait_event(key, "released", 10)
        assert (
            task_request(endpoint, f"/api/v1/learning-tasks/{slow['id']}", token)[
                "version"
            ]
            == version
        )
        rules([])
        resumed, _ = action(endpoint, failed, token, kind="resume")
        assert resumed["status"] == "waiting_student"
        print(
            "Cangjie task deadline passed: 202 receipt, bounded wait, valid late result ignored and recovery"
        )

        cancel = wait_task(endpoint, create(create_question(73))["id"], token)
        key = str(uuid4())
        rules(
            [
                {
                    "key": key,
                    "question_id": cancel["question_id"],
                    "operation": "learning_task",
                    "delay_seconds": 2,
                }
            ]
        )
        queued, _ = submit(cancel)
        wait_event(key, "accepted", 5)
        cancelled = task_request(
            endpoint, f"/api/v1/learning-tasks/{cancel['id']}/cancel", token, {}
        )
        assert cancelled["status"] == "cancelled"
        wait_event(key, "released", 5)
        rules([])
        time.sleep(0.3)
        after = task_request(endpoint, f"/api/v1/learning-tasks/{cancel['id']}", token)
        assert (
            after["status"] == "cancelled"
            and after["version"] == cancelled["version"]
            and not after["learning_applied"]
        )

        # Delay the final SQL update beyond the shared deadline. It must roll
        # back the earlier score, review, exposure, actions and trace writes too.
        final = wait_task(endpoint, create(create_question(75))["id"], token)
        final, _ = action(endpoint, final, token, text="2x=72")
        final, _ = action(endpoint, final, token, text="x=36")
        before = counters(final)
        key = str(uuid4())
        trigger(
            f"CREATE TRIGGER budget_commit_probe BEFORE UPDATE ON learning_tasks FOR EACH ROW SET @zhiwei_budget_delay=IF(NEW.id='{final['id']}' AND NEW.status='completed',SLEEP(8),0)",
        )
        rules(
            [
                {
                    "key": key,
                    "question_id": final["question_id"],
                    "operation": "learning_task",
                    "delay_seconds": 37.5,
                }
            ]
        )
        try:
            queued, body = submit(final, kind="answer", text="x=39")
            failed = wait(queued, 65)
            assert failed["status"] == "failed" and not failed["learning_applied"]
            assert query(
                env, f"SELECT exit_reason FROM learning_tasks WHERE id='{final['id']}'"
            ).startswith("budget_")
            assert counters(final) == before
            assert (
                query(
                    env,
                    f"SELECT status FROM learning_task_actions WHERE task_id='{final['id']}' AND request_id='{body['request_id']}'",
                )
                == "failed"
            )
        finally:
            trigger("DROP TRIGGER IF EXISTS budget_commit_probe")
            rules([])
        final, _ = action(endpoint, failed, token, kind="resume")
        final, _ = action(endpoint, final, token, text="x=39")
        assert final["status"] == "completed" and final["learning_applied"]
        assert (
            query(
                env,
                f"SELECT COUNT(*) FROM cognitive_updates WHERE JSON_UNQUOTE(JSON_EXTRACT(evidence,'$.learning_task_id'))='{final['id']}'",
            )
            == "2"
        )
        assert (
            query(
                env,
                f"SELECT COUNT(*) FROM learning_task_exposures WHERE task_id='{final['id']}'",
            )
            == "1"
        )
        print(
            "Cangjie task budget rollback passed: shared deadline after final SQL, no partial evidence and single recovery update"
        )

        cap = wait_task(endpoint, create(create_question(77))["id"], token)
        query(env, f"UPDATE learning_tasks SET run_count=71 WHERE id='{cap['id']}'")
        queued, body = submit(cap)
        limited = wait(queued)
        assert (
            limited["restart_required"]
            and limited["student_view"]["input_kind"] == "none"
        )
        assert (
            query(env, f"SELECT run_count FROM learning_tasks WHERE id='{cap['id']}'")
            == "72"
        )
        submit(limited, kind="answer", text="2x=74", expected=409)
        replay = task_request(
            endpoint,
            f"/api/v1/learning-tasks/{cap['id']}/actions",
            token,
            body,
            status=202,
        )
        assert replay["version"] == limited["version"]
        task_request(endpoint, f"/api/v1/learning-tasks/{cap['id']}/cancel", token, {})
        new = wait_task(endpoint, create({"id": cap["question_id"]})["id"], token)
        assert new["id"] != cap["id"]
        query(
            env,
            f"UPDATE learning_tasks SET checkpoint=JSON_SET(checkpoint,'$.rounds',24) WHERE id='{new['id']}'",
        )
        limited = task_request(endpoint, f"/api/v1/learning-tasks/{new['id']}", token)
        assert limited["restart_required"]
        submit(limited, kind="hint", expected=409)
        recovery = wait_task(endpoint, create(create_question(79))["id"], token)
        probe = str(uuid4())
        before = counters(recovery)
        query(
            env,
            f"START TRANSACTION; INSERT INTO learning_task_actions (id,task_id,request_id,body_hash,kind,input_version,input_step_id,body,status,created_at,updated_at) VALUES ('{uuid4()}','{recovery['id']}','{probe}','{'a' * 64}','resume',{recovery['version']},'{recovery['step_id']}',JSON_OBJECT('kind','resume','text',''),'pending',UTC_TIMESTAMP(6),UTC_TIMESTAMP(6)); UPDATE learning_tasks SET status='running',run_count=72,version=version+1,lease_token='{uuid4()}',lease_until=UTC_TIMESTAMP()-INTERVAL 1 SECOND,pending_action=JSON_OBJECT('kind','resume','text',''),active_request='{probe}' WHERE id='{recovery['id']}'; COMMIT",
        )
        exhausted = wait(recovery, 10)
        assert exhausted["status"] == "failed" and exhausted["restart_required"]
        assert (
            query(
                env,
                f"SELECT status FROM learning_task_actions WHERE task_id='{recovery['id']}' AND request_id='{probe}'",
            )
            == "failed"
        )
        assert counters(recovery) == before
        print(
            "Cangjie task limits passed: 24 rounds, 72 executions, replay, retained history and explicit restart"
        )
        assert not [r for r in log() if r.get("kind") == "error"], "budget proxy errors"
    finally:
        rules([])
        trigger("DROP TRIGGER IF EXISTS budget_commit_probe")
